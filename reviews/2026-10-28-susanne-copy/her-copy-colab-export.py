    b = (20 + x_shift, 20 + y_shift, 60, 40)

    iou = box_iou_dice(a, b)[0]

    ix0 = max(a[0], b[0])
    iy0 = max(a[1], b[1])
    iw = max(0, min(a[0] + a[2], b[0] + b[2]) - ix0)
    ih = max(0, min(a[1] + a[3], b[1] + b[3]) - iy0)

    intersection = iw * ih
    union = a[2] * a[3] + b[2] * b[3] - intersection

