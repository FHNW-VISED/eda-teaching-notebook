def load_thumb(path, size=(256, 256)):
    with Image.open(path) as im:
        im = im.convert("RGB")
        im.thumbnail(size)
        return im.copy()


def frame(ax, color):
    ax.set_xticks([])
    ax.set_yticks([])
    for spine in ax.spines.values():
        spine.set_visible(True)
