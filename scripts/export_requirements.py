"""Write requirements.txt for people who run the notebook locally with pip instead of Colab.

Every package is pinned to its uv.lock version except the widget packages. The lock pins ipywidgets 7.7.1
because Colab preinstalls it, but local JupyterLab 4 cannot draw ipywidgets 7 widgets ("Module
@jupyter-widgets/base, version ^1.2.0 is not registered"), so the local file swaps in ipywidgets 8 and adds
JupyterLab, which ipywidgets 7 used to pull in by itself. Checked 2026-11-02: both Editions run without errors
on ipywidgets 8, and the browsers draw and respond in JupyterLab 4.6.
Usage: uv run python scripts/export_requirements.py  (or `just requirements`)
"""

from __future__ import annotations

import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCAL_PINS = {"ipywidgets": "8.1.9", "widgetsnbextension": "4.0.16"}  # the ipywidgets 8 pair
EXTRA = ["jupyterlab"]  # pinned through the lock export below
HEADER = (
    "# Packages to run the notebook locally: python3.12 -m venv .venv, then pip install -r requirements.txt\n"
    "# Same versions as uv.lock, except ipywidgets 8: Colab's 7.7.1 does not draw in local JupyterLab 4.\n"
    "# Generated by `just requirements` (scripts/export_requirements.py); do not edit by hand.\n"
)


def run(*args: str) -> str:
    return subprocess.run(args, cwd=ROOT, check=True, capture_output=True, text=True).stdout


def main() -> int:
    locked = run("uv", "export", "--no-dev", "--no-hashes", "--no-emit-project", "--no-header",
                 "--no-annotate", "--format", "requirements-txt")
    swapped = re.compile(rf"^({'|'.join(LOCAL_PINS)})==", re.I)
    constraints = "\n".join(line for line in locked.splitlines() if not swapped.match(line))
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        (tmp / "constraints.txt").write_text(constraints + "\n")
        (tmp / "overrides.txt").write_text("".join(f"{n}=={v}\n" for n, v in LOCAL_PINS.items()))
        (tmp / "extra.in").write_text("\n".join(EXTRA) + "\n")
        out = run("uv", "pip", "compile", "pyproject.toml", str(tmp / "extra.in"),
                  "--constraint", str(tmp / "constraints.txt"), "--override", str(tmp / "overrides.txt"),
                  "--universal", "--python-version", "3.12", "--no-header", "--no-annotate", "--quiet")
    pinned = {re.split(r"[=; ]", line)[0].lower() for line in constraints.splitlines() if "==" in line}
    floating = [line for line in out.splitlines()
                if line and re.split(r"[=; ]", line)[0].lower() not in pinned | set(LOCAL_PINS)]
    if floating:  # a package the lock does not pin would drift with every export
        print("not pinned by uv.lock:", *floating, sep="\n  ", file=sys.stderr)
        return 1
    (ROOT / "requirements.txt").write_text(HEADER + out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
